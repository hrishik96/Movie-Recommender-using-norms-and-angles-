def masked_cosine(a, b):
    mask = ~np.isnan(a) & ~np.isnan(b)
    if mask.sum() == 0:
        return np.nan
    a = a[mask]
    b = b[mask]
    denominator = np.linalg.norm(a) * np.linalg.norm(b)
    return np.dot(a, b) / denominator if denominator != 0 else np.nan

